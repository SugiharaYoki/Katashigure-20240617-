def main():
    OUT.mkdir(parents=True,exist_ok=True)
    manifest=ROOT/'tools/pvp_vfx/generated.json'
    previous=set(json.loads(manifest.read_text())) if manifest.exists() else set()
    make_view();make_profiles();make_specials()
    # Retire obsolete generated rings/displays; never remove handwritten files.
    for old in previous-GENERATED:
        path=ROOT/old
        assert path.is_relative_to(OUT) and path.suffix=='.mcfunction'
        if path.exists():
            assert path.read_text().startswith('# Generated by tools/pvp_vfx/generate.py;')
            path.unlink()
    manifest.write_text(json.dumps(sorted(GENERATED),indent=2)+'\n')
    (ROOT/'tools/pvp_vfx/preview.json').write_text(json.dumps(PREVIEW,separators=(',',':'),ensure_ascii=False)+'\n')
    template=ROOT/'tools/pvp_vfx/preview_template.html'
    if template.exists():
        (ROOT/'tools/pvp_vfx/preview.html').write_text(template.read_text().replace('__GEOMETRY_DATA__',json.dumps(PREVIEW,separators=(',',':'),ensure_ascii=False)))
    print(f'Generated {len(GENERATED)} functions for {len(PROFILES)} skills')

if __name__=='__main__':
    main()
