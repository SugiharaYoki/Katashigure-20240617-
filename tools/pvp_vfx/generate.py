def render(g,p,viewers='@a[distance=..160]',local=False,dust_scale=0.85):
    lines=[];prefix='^' if local else '~'
    for x,y,z,tone in g.points:
        pos=' '.join(prefix+coord(v) for v in (x,y,z))
        lines.append(f'particle minecraft:dust{{color:{rgb(p["a" if tone==0 else "b"])},scale:{dust_scale}}} {pos} 0 0 0 0 1 force {viewers}')
    return lines


def sound(event,volume=1,pitch=1,viewers='@a[distance=..96]'):
    return f'playsound minecraft:{event} player {viewers} ~ ~ ~ {volume} {pitch} 0'


