def write(name, lines):
    path = OUT / (name + '.mcfunction')
    path.parent.mkdir(parents=True, exist_ok=True)
    if isinstance(lines,str): lines = lines.strip().splitlines()
    path.write_text('# Generated by tools/pvp_vfx/generate.py; edit the generator.\n' + '\n'.join(lines) + '\n')
    GENERATED.add(str(path.relative_to(ROOT)))


def rgb(value):
    return '[' + ','.join(f'{int(value[i:i+2],16)/255:.4f}' for i in (0,2,4)) + ']'


def coord(x):
    return f'{0 if abs(x)<0.0005 else x:.3f}'.rstrip('0').rstrip('.')


class Geometry:
    def __init__(self): self.points = []
    def point(self,x,y,z,tone=0): self.points.append((x,y,z,tone))
    def line(self,a,b,tone=0,steps=14):
        for i in range(steps+1):
            t=i/steps; self.point(*(a[j]+(b[j]-a[j])*t for j in range(3)),tone)
    def ring(self,r,y=0,tone=0,phase=0,plane='xz',n=64,center=(0,0,0)):
        for i in range(n):
            a=TAU*i/n+phase; u,v=r*math.cos(a),r*math.sin(a)
            x,yy,z={'xz':(u,y,v),'xy':(u,y+v,0),'yz':(0,y+v,u)}[plane]
            self.point(x+center[0],yy+center[1],z+center[2],tone)
    def polygon(self,r,y,sides,tone=0,phase=0):
        for i in range(sides):
            a=TAU*i/sides+phase;b=TAU*(i+1)/sides+phase
            self.line((r*math.cos(a),y,r*math.sin(a)),(r*math.cos(b),y,r*math.sin(b)),tone,10)
    def helix(self,r,h,turns=2,phase=0,tone=0,n=100):
        for i in range(n):
            t=i/(n-1);a=TAU*turns*t+phase
            self.point(r*math.cos(a),h*t,r*math.sin(a),tone)
    def star(self,r,y=0,points=6,tone=0,phase=0):
        for i in range(points):
            a=TAU*i/points+phase; b=TAU*((i+2)%points)/points+phase
            self.line((r*math.cos(a),y,r*math.sin(a)),(r*math.cos(b),y,r*math.sin(b)),tone,12)
    def box(self,r,y,h,tone=0):
        corners=[(-r,y,-r),(r,y,-r),(r,y,r),(-r,y,r)]
        for i,a in enumerate(corners):
            b=corners[(i+1)%4]
            self.line(a,b,tone,10);self.line((a[0],y+h,a[2]),(b[0],y+h,b[2]),tone,10)
            self.line(a,(a[0],y+h,a[2]),tone,12)


def geometry(shape,t,scale=1):
    """Each silhouette has a deliberately different spatial/temporal rhythm."""
    g=Geometry(); phase=TAU*t; ease=1-(1-t)**3; r=(0.6+2.3*ease)*scale
    if shape=='crystal':
        g.ring(r,.2,0,phase);g.ring(r*.7,1.1,1,-phase,plane='xy')
        for i in range(6):
            a=TAU*i/6+phase;x,z=r*.6*math.cos(a),r*.6*math.sin(a)
            for dx,dz in ((.35,0),(-.35,0),(0,.35),(0,-.35)):
                g.line((x,2.8,z),(x+dx,1.2,z+dz),i%2,8);g.line((x,.3,z),(x+dx,1.2,z+dz),i%2,8)
    elif shape in ('wings','seraph'):
        g.ring(r,.15,1);g.ring(.8+ease,2.6,0,phase,plane='xy')
        for side in (-1,1):
            for j in range(9):
                tip=(side*(1.5+j*.28)*ease,1.4+math.sin(j/9*math.pi)*2.8,-.4-j*.1)
                g.line((side*.2,1.5,-.2),tip,j%2,24)
                g.line(tip,(tip[0]*.67,tip[1]-.9,tip[2]-.3),1,9)
        if shape=='seraph':g.helix(r*.6,5,3,-phase,0,140)
    elif shape in ('shield','bastion'):
        g.polygon(r,.12,6,0,phase*.12);g.polygon(r,2.5*ease,6,1,phase*.12)
        for i in range(6):
            a=TAU*i/6+phase*.12;x,z=r*math.cos(a),r*math.sin(a)
            g.line((x,0,z),(x,3.8*ease,z),0,20)
        if shape=='bastion':g.box(r*.65,0,4*ease,1)
        else:
            for a in (0,TAU/3,2*TAU/3):g.ring(1.5*scale,1.5,1,a,plane='xy',n=48,center=(math.sin(a)*.5,0,math.cos(a)*.5))
    elif shape in ('storm','judgment'):
        g.star(r,.1,6,0,phase*.2);g.ring(r*1.1,.1,1)
        for j in range(5):
            a=TAU*j/5;px,pz=r*.7*math.cos(a),r*.7*math.sin(a)
            for k in range(16):
                y=k*.75;ny=(k+1)*.75
                q=math.sin(k*7.3+j+phase)*.45
                q2=math.sin((k+1)*7.3+j+phase)*.45
                g.line((px+q,y,pz-q/2),(px+q2,ny,pz-q2/2),j%2,3)
        if shape=='judgment':g.ring(r,6,1);g.line((0,0,0),(0,10,0),1,70)
    elif shape in ('slash','crescent'):
        for j in range(3):
            for i in range(96):
                a=(-.8+1.6*i/95)*math.pi+phase*.25
                rr=r*(1-j*.10);g.point(rr*math.cos(a),1.1+rr*math.sin(a)*.55,(j-1)*.24, j%2)
        if shape=='crescent':g.ring(r*.8,.1,1,phase)
    elif shape=='bones':
        g.star(r,.05,5,1,-phase*.2)
        for j in range(8):
            a=TAU*j/8
            for k in range(36):
                q=math.pi*k/35;rr=r*math.sin(q)
                g.point(rr*math.cos(a),3.8*(1-math.cos(q))/2,rr*math.sin(a),j%2)
        g.helix(.5,4.8,3,phase,0,80)
    elif shape=='crown':
        g.ring(r,.1,1);g.ring(r*.7,2.2,0)
        for i in range(8):
            a=TAU*i/8; b=a+TAU/16;c=a+TAU/8
            g.line((r*.7*math.cos(a),2.2,r*.7*math.sin(a)),(r*math.cos(b),3.5,r*math.sin(b)),0)
            g.line((r*math.cos(b),3.5,r*math.sin(b)),(r*.7*math.cos(c),2.2,r*.7*math.sin(c)),1)
    elif shape in ('gravity','abyss'):
        for j in range(3):g.ring(r*(1-j*.2),.15+j*.65,j%2,phase*(j+1))
        g.helix(r*.65,8 if shape=='abyss' else 4,3,phase,0,150)
